// Generate assets/css/katex.css — KaTeX's stylesheet with every font inlined as a
// base64 data: URI. The vendor katex.min.css references fonts by relative path
// (url(fonts/*.woff2)); in dev Vite rewrites those to absolute dev-origin URLs
// (http://localhost:3031/_nuxt/@fs/…), which fail with ERR_CONNECTION_REFUSED from
// any renderer that isn't the live dev origin (the tray popover window, or after a
// dev-server restart). Inlining removes the network fetch entirely, so LaTeX math
// renders identically under dev, `nuxt build`, and the app:// protocol.
//
// Only the woff2 face is inlined (dropping the woff/ttf fallbacks) — every Chromium
// AWOG ships on supports woff2, and it keeps the emitted CSS ~1/3 the size.
//
// Re-run after bumping the `katex` dependency:  node scripts/inline-katex-fonts.mjs

import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const cssPath = require.resolve('katex/dist/katex.min.css')
const fontsDir = join(dirname(cssPath), 'fonts')
const outPath = resolve(fileURLToPath(new URL('.', import.meta.url)), '../assets/css/katex.css')

const css = readFileSync(cssPath, 'utf8')

let inlined = 0
// Replace each @font-face `src` (woff2 + woff/ttf fallbacks) with a single woff2
// data URI. `[^;}]*` eats the trailing fallback url()s up to the rule's end.
const out = css.replace(
  /src:url\(fonts\/([\w-]+)\.woff2\) format\("woff2"\)[^;}]*/g,
  (_m, name) => {
    const b64 = readFileSync(join(fontsDir, `${name}.woff2`)).toString('base64')
    inlined += 1
    return `src:url(data:font/woff2;base64,${b64}) format("woff2")`
  },
)

if (!inlined) throw new Error('inline-katex-fonts: no woff2 url() matched — CSS format changed?')

const banner = `/* GENERATED by scripts/inline-katex-fonts.mjs — do not edit by hand.\n   KaTeX stylesheet with ${inlined} fonts inlined as data: URIs (no network fetch). */\n`
writeFileSync(outPath, banner + out)
process.stdout.write(`inline-katex-fonts: inlined ${inlined} fonts → ${outPath}\n`)
